    internal static Locale Detect() => Detect(CultureInfo.CurrentUICulture);
    internal static Locale Detect(CultureInfo culture)
    {
        var language = culture.TwoLetterISOLanguageName.ToLowerInvariant();
        return new Locale(language == "en" ? CreateEnglish() : CreatePolish());
    }

    internal string T(string key) => strings.TryGetValue(key, out var value) ? value : key;
    internal string F(string key, params object[] args) => string.Format(CultureInfo.CurrentUICulture, T(key), args);

    internal Dictionary<string, string> Values => strings;

